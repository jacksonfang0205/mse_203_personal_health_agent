/**
 * Build golden references from the "good" clips in data/form/clips and write
 * them to src/lib/form/references, where the app and the agent read them.
 *
 *   npm run form:references
 *   npm run form:references -- --exclude squat_good_03   # hold a clip out for evals
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildReference } from "../../src/lib/form/golden";
import { MOVEMENTS } from "../../src/lib/form/movements";
import { loadClips } from "./clips";

const exclude = new Set(
  process.argv.flatMap((a, i, all) => (a === "--exclude" ? (all[i + 1] ?? "").split(",") : [])).filter(Boolean),
);
const clips = loadClips().filter((c) => !exclude.has(c.id));
const outDir = join(process.cwd(), "src", "lib", "form", "references");
const built: string[] = [];

for (const m of Object.values(MOVEMENTS)) {
  const good = clips.filter((c) => c.movementId === m.id && c.label === "good");
  if (!good.length) {
    console.log(`${m.id}: no good clips, skipped`);
    continue;
  }
  try {
    const ref = buildReference(m, good);
    writeFileSync(join(outDir, `${m.id}.json`), JSON.stringify(ref, null, 2) + "\n");
    built.push(m.id);
    console.log(`${m.id}: ${ref.clipIds.length} clips, ${ref.reps} reps -> references/${m.id}.json`);
  } catch (e) {
    console.log(`${m.id}: ${(e as Error).message}`);
  }
}

const imports = built.map((id) => `import ${id} from "./${id}.json";`).join("\n");
const entries = built.map((id) => `  ${id}: GoldenReference.parse(${id}),`).join("\n");
writeFileSync(
  join(outDir, "index.ts"),
  `/**
 * Golden references by movement id.
 * Generated by \`npm run form:references\` from data/form/clips. Do not edit by hand.
 */
import { GoldenReference } from "../golden";
${imports}

export const REFERENCES: Record<string, GoldenReference> = {
${entries}
};
`,
);
console.log(`Wrote references/index.ts with ${built.length} movement(s).`);
